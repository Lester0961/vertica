const generateBillSchema = z.object({
  leaseId: z.string().uuid(),
  periodStart: z.iso.date(),
  periodEnd: z.iso.date(),
  dueDate: z.iso.date(),
});

async function generateBillHandler(ctx: ApiContext) {
  let body: unknown;
  try { body = await ctx.req.json(); } catch { return fail("BAD_REQUEST", "Invalid JSON body."); }
  const parsed = generateBillSchema.safeParse(body);
  if (!parsed.success) return fail("BAD_REQUEST", "Complete the billing period and due date.", { issues: parsed.error.issues });
  try { return ok(await generateMonthlyBill(parsed.data)); }
  catch (error) { return fail("UNPROCESSABLE", (error as Error).message); }
}

const submitSchema = z.object({
  billId: z.string().uuid(),
  amount: z.number().positive().max(100_000_000),
  method: z.enum(["BANK_TRANSFER", "GCASH", "PAYMAYA", "CARD", "OVER_THE_COUNTER", "OTHER"]),
  externalReference: z.string().max(200).optional(),
});

async function submitPaymentHandler(ctx: ApiContext) {
  let body: unknown;
  try {
    body = await ctx.req.json();
  } catch {
    return fail("BAD_REQUEST", "Invalid JSON body.");
  }
  const parsed = submitSchema.safeParse(body);
  if (!parsed.success) return fail("BAD_REQUEST", "Invalid payment.", { issues: parsed.error.issues });
  try {
    const result = await submitPayment(parsed.data);
    return ok(result);
  } catch (e) {
    return fail("FORBIDDEN", (e as Error).message);
  }
}

const verifySchema = z.object({
  decision: z.enum(["APPROVED", "PARTIALLY_APPROVED", "REJECTED"]),
  approvedAmount: z.number().positive().max(100_000_000).optional(),
  reason: z.string().trim().min(1).max(2000).optional(),
}).superRefine((value, ctx) => {
  if (value.decision === "REJECTED" && !value.reason) {
    ctx.addIssue({ code: "custom", path: ["reason"], message: "A rejection reason is required." });
  }
  if (value.decision === "PARTIALLY_APPROVED" && (!value.reason || value.approvedAmount === undefined)) {
    ctx.addIssue({ code: "custom", path: ["reason"], message: "A partial approval amount and reason are required." });
  }
  if (value.decision === "APPROVED" && value.approvedAmount === undefined) {
    ctx.addIssue({ code: "custom", path: ["approvedAmount"], message: "An approved amount is required." });
  }
});

async function verifyPaymentHandler(ctx: ApiContext) {
  const paymentId = ctx.params?.id;
  if (!paymentId) return fail("BAD_REQUEST", "Missing payment id.");
  let body: unknown;
  try {
    body = await ctx.req.json();
  } catch {
    return fail("BAD_REQUEST", "Invalid JSON body.");
  }
  const parsed = verifySchema.safeParse(body);
  if (!parsed.success) return fail("BAD_REQUEST", "Invalid review decision.", { issues: parsed.error.issues });
  try {
    return ok(await verifyPayment({ paymentId, ...parsed.data }));
  } catch (e) {
    return fail("FORBIDDEN", (e as Error).message);
  }
}

export function registerBillingRoutes(): void {
  register("GET", "billing/me/bills", billsHandler);
  register("GET", "billing/me/bills/:id/invoice", invoiceHandler);
  register("GET", "billing/me/payments", paymentsHandler);
  register("POST", "billing/me/payments", submitPaymentHandler);
  register("GET", "billing/all/bills", allBillsHandler);
  register("GET", "billing/all/payments", allPaymentsHandler);
  register("POST", "billing/bills", generateBillHandler);
  register("POST", "billing/payments/:id/verify", verifyPaymentHandler);
}
